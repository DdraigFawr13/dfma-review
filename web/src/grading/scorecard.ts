// The two scorecard makers on the browser engine (the browser engine's tests/nist/make_scorecard.py and
// tests/edmr/make_scorecard.py). Each file runs in its own process (run.ts); numbers may only improve (D-011).
//   node scripts/grading.mjs nist-scorecard [--out file] [--jobs N]   from tests/nist/.cache/NIST-PMI-STEP-Files (unzip
//       tests/nist/NIST-PMI-STEP-Files.zip into tests/nist/.cache first), the AP242 files
//   node scripts/grading.mjs edmr-scorecard [--out file] [--jobs N]   from tests/edmr/models
import { existsSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { parseArgs } from "node:util";
import { pool, runChild } from "./run.ts";

const ROOT = resolve(fileURLToPath(new URL(".", import.meta.url)), "../../..");
const NIST_DIR = join(ROOT, "tests", "nist");
const EDMR_DIR = join(ROOT, "tests", "edmr");

interface Counts { status: string; face_count: number; not_analysed: number; features: number }

/** The AP242 files of the NIST zip, sorted (nist_files.ap242_files, with the zip already unpacked). */
export function nistFiles(): string[] {
  const folder = join(NIST_DIR, ".cache", "NIST-PMI-STEP-Files");
  if (!existsSync(folder)) throw new Error(`${folder} is missing: unzip tests/nist/NIST-PMI-STEP-Files.zip into tests/nist/.cache`);
  return readdirSync(folder).filter((n) => /^.*_ap242.*\.stp$/.test(n)).sort().map((n) => join(folder, n));
}

/** Every .stp and .step under tests/edmr/models, in Python's path order (compared part by part, not as text). */
export function edmrFiles(): string[] {
  const out: string[] = [];
  const walk = (dir: string) => {
    for (const n of readdirSync(dir)) {
      const p = join(dir, n);
      if (statSync(p).isDirectory()) walk(p);
      else if (/\.(stp|step)$/i.test(n)) out.push(p);
    }
  };
  walk(join(EDMR_DIR, "models"));
  const parts = (p: string) => relative(EDMR_DIR, p).split("/");
  return out.sort((a, b) => {
    const [x, y] = [parts(a), parts(b)];
    for (let i = 0; i < Math.min(x.length, y.length); i++) if (x[i] !== y[i]) return x[i] < y[i] ? -1 : 1;
    return x.length - y.length;
  });
}

/** The text of tests/nist/scorecard.toml. */
export function nistToml(files: { name: string; o: Counts }[]): string {
  const out = ["# Generated by tests/nist/make_scorecard.py; numbers may only improve (D-011).", ""];
  for (const { name, o } of files) out.push("[[file]]", `name = "${name}"`, `face_count = ${o.face_count}`, `not_analysed = ${o.not_analysed}`, `features = ${o.features}`, "");
  return out.join("\n");
}

/** The text of tests/edmr/scorecard.toml. */
export function edmrToml(files: { path: string; o: Counts }[]): string {
  const out = ["# Generated by tests/edmr/make_scorecard.py; results may only improve (D-011).", ""];
  for (const { path, o } of files) {
    out.push("[[file]]", `path = "${path}"`, `status = "${o.status}"`, `face_count = ${o.face_count}`, `not_analysed = ${o.not_analysed}`, `features = ${o.features}`, "");
  }
  return out.join("\n");
}

async function main(): Promise<number> {
  const { positionals, values: a } = parseArgs({ allowPositionals: true, options: { out: { type: "string" }, jobs: { type: "string", default: "4" } } });
  const which = positionals[0];
  if (which !== "nist" && which !== "edmr") {
    console.error("usage: scorecard <nist|edmr> [--out file] [--jobs N]");
    return 2;
  }
  const paths = which === "nist" ? nistFiles() : edmrFiles();
  const counts = await pool(paths, Number(a.jobs), async (p, n) => {
    const r = (await runChild("counts", p)) as unknown as Counts;
    console.error(`scorecard ${which} [${n + 1}/${paths.length}] ${r.status}: ${relative(ROOT, p)}`);
    return r;
  });
  // A timeout or a dead process is the browser engine's "crash"; the NIST card has no status (Python had none and stopped on a crash)
  const o = (r: Counts): Counts => (r.status === "ok" || r.status === "read_error" ? r : { status: "crash", face_count: 0, not_analysed: 0, features: 0 });
  const text = which === "nist"
    ? nistToml(paths.map((p, i) => ({ name: p.slice(p.lastIndexOf("/") + 1), o: o(counts[i]) })))
    : edmrToml(paths.map((p, i) => ({ path: relative(EDMR_DIR, p).split("\\").join("/"), o: o(counts[i]) })));
  writeFileSync(a.out ?? join(which === "nist" ? NIST_DIR : EDMR_DIR, "scorecard.toml"), text, { encoding: "utf8" });
  console.log(which === "nist" ? `wrote ${paths.length} files to scorecard.toml` : `wrote ${paths.length} files`);
  return 0;
}

if (process.argv[1] && import.meta.url === new URL(process.argv[1], "file:").href) process.exit(await main());
