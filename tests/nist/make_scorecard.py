"""Write tests/nist/scorecard.toml from what the tool maps on each NIST AP242 file today.

Run from the repo root inside the dfma environment after a slice improves the map:
    python tests/nist/make_scorecard.py
Review the diff: numbers may only move towards a complete map (D-011).
"""

from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path[:0] = [str(ROOT / "tests"), str(ROOT / "service")]

from dfma.analyze import analyze  # noqa: E402
from nist_files import NIST_DIR, ap242_files  # noqa: E402


def main() -> int:
    out = ["# Generated by tests/nist/make_scorecard.py; numbers may only improve (D-011).", ""]
    for path in ap242_files():
        r = analyze(path, path.name)
        out += ["[[file]]", f'name = "{path.name}"', f'face_count = {r["part"]["face_count"]}',
                f'not_analysed = {len(r["part"]["not_analysed_faces"])}', f'features = {len(r["features"])}', ""]
    (NIST_DIR / "scorecard.toml").write_text("\n".join(out), encoding="utf-8", newline="\n")
    print(f"wrote {sum(1 for l in out if l == '[[file]]')} files to scorecard.toml")
    return 0


if __name__ == "__main__":
    sys.exit(main())
