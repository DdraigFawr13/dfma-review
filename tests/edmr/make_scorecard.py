"""Write tests/edmr/scorecard.toml from what the tool does with each EDMR STEP file today.

Run from the repo root inside the dfma environment:  python tests/edmr/make_scorecard.py
It runs every file through the analysis worker, so a file that crashes OpenCascade is
recorded as "crash" instead of stopping the run. Review the diff: results may only improve.
"""

from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
HERE = ROOT / "tests" / "edmr"
sys.path[:0] = [str(ROOT / "service")]


def files() -> list[Path]:
    return sorted(p for p in (HERE / "models").rglob("*") if p.suffix.lower() in (".stp", ".step"))


def outcome(path: Path, run) -> dict:
    from dfma.errors import ReadError
    try:
        r = run(path, path.name, "mill", "al6061")
    except ReadError:
        return {"status": "read_error", "face_count": 0, "not_analysed": 0, "features": 0}
    except RuntimeError:  # the worker stopped: OpenCascade crashed on this file
        return {"status": "crash", "face_count": 0, "not_analysed": 0, "features": 0}
    return {"status": "ok", "face_count": r["part"]["face_count"],
            "not_analysed": len(r["part"]["not_analysed_faces"]), "features": len(r["features"])}


def main() -> int:
    from dfma.worker import run_analysis
    out = ["# Generated by tests/edmr/make_scorecard.py; results may only improve (D-011).", ""]
    for path in files():
        o = outcome(path, run_analysis)
        out += ["[[file]]", f'path = "{path.relative_to(HERE).as_posix()}"', f'status = "{o["status"]}"',
                f'face_count = {o["face_count"]}', f'not_analysed = {o["not_analysed"]}', f'features = {o["features"]}', ""]
    (HERE / "scorecard.toml").write_text("\n".join(out), encoding="utf-8", newline="\n")
    print(f"wrote {sum(1 for l in out if l == '[[file]]')} files")
    return 0


if __name__ == "__main__":
    sys.exit(main())
